for name, phrases in BANK.items():
    seen, clean = set(), []
    for ph in phrases:
        n = norm(ph)
        if n and n not in seen:
            seen.add(n)
            clean.append(ph)
    with open(OUT / f"{name}.json", "w", encoding="utf-8") as f:
        json.dump(clean, f, indent=1, ensure_ascii=False)
    print(name, len(clean))